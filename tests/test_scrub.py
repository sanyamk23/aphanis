class TestScrubPythonAPI(unittest.TestCase):
    """The Python API: clean_text with the hygiene-only flags."""

    def test_clean_text_no_humanize_no_perturb(self):
        text = "Furthermore, we must delve into this crucial testament."
        out = clean_text(
            text,
            perturb_stats=False,
            clean_ai_comments=True,
            mode=None,
            humanize=False,
        )
        self.assertIn("delve", out)
        self.assertIn("crucial", out)
        self.assertIn("Furthermore", out)
        # Hygiene does not rewrite
        self.assertNotIn("we've got to", out)
        self.assertNotIn("explore", out)  # perturb would have swapped delve -> explore

    def test_clean_text_strips_ai_comments(self):
        text = "# Generated by Claude\nhello"
        out = clean_text(text, humanize=False, perturb_stats=False)
        self.assertNotIn("Generated by Claude", out)
        self.assertIn("hello", out)

    def test_clean_text_strips_zwsp(self):
        text = f"ab{ZWJ}cd{ZWNJ}ef{BOM}gh"
        out = clean_text(text, humanize=False, perturb_stats=False)
        self.assertNotIn(ZWSP, out)
        self.assertNotIn(ZWNJ, out)
        self.assertNotIn(ZWJ, out)
        self.assertNotIn(BOM, out)
        self.assertEqual(out, "abcdefgh")


