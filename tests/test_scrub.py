class TestScrubFileHygiene(unittest.TestCase):
    """scrub-file must strip metadata + invisible Unicode, not humanize or pixel-jitter."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()

    def tearDown(self):
        import shutil
        shutil.rmtree(self.tmp, ignore_errors=True)

    def _write(self, name, content):
        path = os.path.join(self.tmp, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return path

    def test_text_file_zwsp_stripped(self):
        path = self._write("zw.txt", f"Hello world{ZWJ}with{ZWNJ}zero{BOM}width chars.\n")
        result = run_aphanis(["scrub-file", "--i-own-this-content", path])
        self.assertEqual(result.returncode, 0, result.stderr)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        self.assertNotIn(ZWSP, content)
        self.assertNotIn(ZWNJ, content)
        self.assertNotIn(ZWJ, content)
        self.assertNotIn(BOM, content)
        self.assertIn("Hello world", content)
        self.assertIn("with", content)
        self.assertIn("zero", content)
        self.assertIn("width", content)

    def test_text_file_ai_comment_stripped(self):
        path = self._write("code.py", "# Generated by Claude\ndef hello(): return 1\n")
        result = run_aphanis(["scrub-file", "--i-own-this-content", path])
        self.assertEqual(result.returncode, 0, result.stderr)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        self.assertNotIn("Generated by Claude", content)
        self.assertIn("def hello()", content)

    def test_text_file_does_not_humanize(self):
        # Hygiene path: text content of a file should not be humanized
        path = self._write("x.md", "Furthermore, we must consider this.\n")
        result = run_aphanis(["scrub-file", "--i-own-this-content", path])
        self.assertEqual(result.returncode, 0, result.stderr)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        self.assertIn("Furthermore", content)
        self.assertIn("we must", content)

    def test_docx_metadata_cleared(self):
        import docx
        path = os.path.join(self.tmp, "test.docx")
        doc = docx.Document()
        doc.core_properties.author = "Claude"
        doc.core_properties.comments = "Generated by Claude"
        doc.core_properties.keywords = "AI"
        doc.core_properties.subject = "watermark test"
        doc.core_properties.title = "t"
        doc.add_paragraph("Hello world.")
        doc.save(path)

        result = run_aphanis(["scrub-file", "--i-own-this-content", path])
        self.assertEqual(result.returncode, 0, result.stderr)

        doc2 = docx.Document(path)
        cp = doc2.core_properties
        self.assertEqual(cp.author, "")
        self.assertEqual(cp.comments, "")
        self.assertEqual(cp.keywords, "")
        self.assertEqual(cp.subject, "")
        self.assertEqual(cp.title, "")
        self.assertEqual(doc2.paragraphs[0].text, "Hello world.")

    def test_missing_file(self):
        path = os.path.join(self.tmp, "does_not_exist.txt")
        result = run_aphanis(["scrub-file", "--i-own-this-content", path])
        self.assertEqual(result.returncode, 1)
        self.assertIn("not found", result.stderr.lower())


