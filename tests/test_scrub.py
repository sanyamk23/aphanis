"""
Tests for the scrub-text and scrub-file CLI subcommands (Feature 5:
legitimate hygiene reframing).

The scrub subcommands are the hygiene-only path: they strip invisible
Unicode and AI-attribution comments / file metadata, but they do NOT
humanize or perturb statistical AI vocabulary. They require an explicit
--i-own-this-content confirmation flag.
"""

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from aphanis.cleaner import clean_text


REPO_ROOT = Path(__file__).resolve().parent.parent
PYTHON = sys.executable

# ZWSP family: use chr() to avoid having actual control chars in the
# source file, which get mangled by editors and copy-paste.
ZWSP = chr(0x200B)
ZWNJ = chr(0x200C)
ZWJ = chr(0x200D)
BOM = chr(0xFEFF)


def run_aphanis(args, stdin=None):
    """Run `python -m aphanis.cli <args>` and return CompletedProcess."""
    return subprocess.run(
        [PYTHON, "-m", "aphanis.cli", *args],
        capture_output=True,
        text=True,
        input=stdin,
        cwd=str(REPO_ROOT),
    )


class TestScrubTextHygiene(unittest.TestCase):
    """scrub-text must strip invisible Unicode + AI comments, but not humanize."""

    def test_strips_zero_width_chars(self):
        result = run_aphanis(
            ["scrub-text", "--i-own-this-content"],
            stdin=f"Hello world{ZWJ}with{ZWNJ}zero{BOM}width chars.",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        # Zero-width family gone
        self.assertNotIn(ZWSP, result.stdout)
        self.assertNotIn(ZWNJ, result.stdout)
        self.assertNotIn(ZWJ, result.stdout)
        self.assertNotIn(BOM, result.stdout)
        # Visible text preserved
        self.assertIn("Hello world", result.stdout)
        self.assertIn("with", result.stdout)
        self.assertIn("zero", result.stdout)
        self.assertIn("width", result.stdout)
        self.assertIn("chars", result.stdout)

    def test_strips_ai_comments(self):
        result = run_aphanis(
            ["scrub-text", "--i-own-this-content"],
            stdin="# Generated by Claude\ndef hello(): return 1\n",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertNotIn("Generated by Claude", result.stdout)
        self.assertIn("def hello()", result.stdout)

    def test_does_not_humanize(self):
        original = "Furthermore, we must consider the implications."
        result = run_aphanis(
            ["scrub-text", "--i-own-this-content"],
            stdin=original,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        # Hygiene should not run humanize: "we must" should pass through
        # unchanged (humanizer would rewrite it).
        self.assertIn("Furthermore", result.stdout)
        self.assertIn("we must", result.stdout)
        self.assertIn("consider", result.stdout)

    def test_does_not_perturb_ai_vocabulary(self):
        # Hygiene must NOT run StatisticalPerturber. Vocabulary telltales
        # like "delve" should pass through unchanged.
        original = "We need to delve into the crucial aspects."
        result = run_aphanis(
            ["scrub-text", "--i-own-this-content"],
            stdin=original,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("delve", result.stdout)
        self.assertIn("crucial", result.stdout)

    def test_empty_input(self):
        result = run_aphanis(["scrub-text", "--i-own-this-content"], stdin="")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, "")

    def test_inline_text_argument(self):
        result = run_aphanis(
            ["scrub-text", "--i-own-this-content", "hello world"],
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("hello", result.stdout)
        self.assertIn("world", result.stdout)


