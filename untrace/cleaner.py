class UnicodeSanitizer:
    """Strips hidden zero-width spaces, tracking tags, variation selectors, homoglyphs, and punctuation telltales."""

    # Complete zero-width & invisible characters used for steganography / LLM watermarking
    ZERO_WIDTH_CHARS = {
        '\u200B': 'Zero-Width Space',
        '\u200C': 'Zero-Width Non-Joiner',
        '\u200D': 'Zero-Width Joiner',
        '\uFEFF': 'Zero-Width No-Break Space (BOM)',
        '\u2060': 'Word Joiner',
        '\u2061': 'Function Application',
        '\u2062': 'Invisible Times',
        '\u2063': 'Invisible Separator',
        '\u2064': 'Invisible Plus',
        '\u00AD': 'Soft Hyphen',
        '\u180E': 'Mongolian Vowel Separator',
    }

    # Bidi & direction override characters
    BIDI_CHARS = {
        '\u200E': 'Left-to-Right Mark',
        '\u200F': 'Right-to-Left Mark',
        '\u202A': 'Left-to-Right Embedding',
        '\u202B': 'Right-to-Left Embedding',
        '\u202C': 'Pop Directional Formatting',
        '\u202D': 'Left-to-Right Override',
        '\u202E': 'Right-to-Left Override',
        '\u2066': 'Left-to-Right Isolate',
        '\u2067': 'Right-to-Left Isolate',
        '\u2068': 'First Strong Isolate',
        '\u2069': 'Pop Directional Isolate'
    }

    # Custom space normalization
    SPACE_NORMALIZATIONS = {
        '\u00A0': 'Non-breaking space',
        '\u2002': 'En space',
        '\u2003': 'Em space',
        '\u2004': 'Three-per-em space',
        '\u2005': 'Four-per-em space',
        '\u2006': 'Six-per-em space',
        '\u2007': 'Figure space',
        '\u2008': 'Punctuation space',
        '\u2009': 'Thin space',
        '\u200A': 'Hair space',
        '\u202F': 'Narrow no-break space',
        '\u205F': 'Medium mathematical space',
        '\u3000': 'Ideographic space',
    }

    # Punctuation homoglyphs & LLM formatting telltales
    PUNCTUATION_REPLACEMENTS = {
        '“': '"',  # Left double smart quote
        '”': '"',  # Right double smart quote
        '‘': "'",  # Left single smart quote
        '’': "'",  # Right single smart quote
        '—': ' - ', # Em-dash (Claude signature telltale) -> space-hyphen-space
        '–': '-',  # En-dash -> standard hyphen
        '…': '...',# Ellipsis character -> three dots
    }

    @classmethod
    def clean(cls, text: str, normalize_unicode: bool = True, clean_punctuation: bool = True) -> str:
        """Strips invisible watermarking characters, variation selectors, normalizes quotes/dashes & Unicode."""
        if not text:
            return ""

        # 1. Remove Tag Characters (\uE0001 - \uE007F) & Variation Selectors (\uFE00 - \uFE0F, \uE0100 - \uE01EF)
        cleaned_chars = []
        for c in text:
            code = ord(c)
            if 0xE0001 <= code <= 0xE007F:
                continue
            if 0xFE00 <= code <= 0xFE0F or 0xE0100 <= code <= 0xE01EF:
                continue
            cleaned_chars.append(c)

        text = "".join(cleaned_chars)

        # 2. Filter zero-width & bidi characters, normalize non-standard space codes
        chars = []
        for char in text:
            if char in cls.ZERO_WIDTH_CHARS or char in cls.BIDI_CHARS:
                continue
            if char in cls.SPACE_NORMALIZATIONS:
                chars.append(' ')
            elif clean_punctuation and char in cls.PUNCTUATION_REPLACEMENTS:
                chars.append(cls.PUNCTUATION_REPLACEMENTS[char])
            else:
                chars.append(char)
        text = "".join(chars)

        # 3. Unicode NFKC Normalization
        if normalize_unicode:
            text = unicodedata.normalize("NFKC", text)

        # 4. Clean consecutive space artifacts created by stripping
        text = re.sub(r'[ \t]+', ' ', text)
        
        # 5. Remove trailing space per line
        lines = [line.rstrip() for line in text.splitlines()]
        return "\n".join(lines)


class AICommentSanitizer:
    """Strips AI code comments, watermarks, and generated header annotations."""

    SINGLE_LINE_PATTERNS = [
        r'#\s*(?:Generated by|Created by|Co-authored-by:|Modified by|AI-generated|Claude|ChatGPT|LLM).*',
        r'//\s*(?:Generated by|Created by|Co-authored-by:|Modified by|AI-generated|Claude|ChatGPT|LLM).*',
        r'@generated.*',
    ]

    MULTI_LINE_PATTERNS = [
        r'/\*\s*(?:Generated by|Created by|Co-authored-by:|Modified by|AI-generated|Claude|ChatGPT|LLM).*?\*/',
        r'<!--\s*(?:Generated by|Created by|Co-authored-by:|Modified by|AI-generated|Claude|ChatGPT|LLM).*?-->',
    ]

    @classmethod
    def clean(cls, text: str) -> str:
        """Removes AI signatures and generated code comments."""
        if not text:
            return ""

        result = text
        for pattern in cls.SINGLE_LINE_PATTERNS:
            result = re.sub(pattern, '', result, flags=re.IGNORECASE)

        for pattern in cls.MULTI_LINE_PATTERNS:
            result = re.sub(pattern, '', result, flags=re.IGNORECASE | re.DOTALL)
        
        # Remove empty comment lines
        lines = [line for line in result.splitlines() if line.strip() != '' or line == '']
        return "\n".join(lines)


