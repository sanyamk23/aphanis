class ImageWatermarkDisrupter:
    """Modulates image LSB pixel noise to disrupt frequency-domain spatial watermarks."""

    @classmethod
    def perturb_image(cls, file_path: str, jitter: bool = True) -> Tuple[bool, str]:
        """Strips EXIF/C2PA metadata and applies perceptual sub-pixel noise jitter."""
        try:
            from PIL import Image
            img = Image.open(file_path)
            mode = img.mode
            size = img.size
            pixels = list(img.getdata())

            if jitter and mode in ('RGB', 'RGBA'):
                new_pixels = []
                for p in pixels:
                    if mode == 'RGB':
                        r, g, b = p
                        r = max(0, min(255, r + random.choice([-1, 0, 1])))
                        new_pixels.append((r, g, b))
                    else:
                        r, g, b, a = p
                        r = max(0, min(255, r + random.choice([-1, 0, 1])))
                        new_pixels.append((r, g, b, a))
                pixels = new_pixels

            img_cleaned = Image.new(mode, size)
            img_cleaned.putdata(pixels)
            img_cleaned.save(file_path)
            return True, f"Stripped metadata & perturbed spatial watermarks for {file_path}"
        except Exception as e:
            return False, f"Failed to process image: {str(e)}"


class AuditTool:
    """Audits text and files for invisible zero-width watermarks, C2PA signatures, and AI telltales."""

    @classmethod
    def audit_text(cls, text: str) -> Dict[str, Any]:
        """Scans text for zero-width characters, em-dashes, AI comments, and telltale phrases."""
        if not text:
            return {"status": "CLEAN", "score": 100, "issues": []}

        issues = []
        zero_width_count = 0
        bidi_count = 0
        tag_char_count = 0
        em_dash_count = text.count('—')
        smart_quote_count = text.count('“') + text.count('”') + text.count('‘') + text.count('’')

        for c in text:
            code = ord(c)
            if c in UnicodeSanitizer.ZERO_WIDTH_CHARS:
                zero_width_count += 1
            if c in UnicodeSanitizer.BIDI_CHARS:
                bidi_count += 1
            if 0xE0001 <= code <= 0xE007F or 0xFE00 <= code <= 0xFE0F:
                tag_char_count += 1

        if zero_width_count > 0:
            issues.append(f"Found {zero_width_count} hidden zero-width / invisible tracking characters")
        if bidi_count > 0:
            issues.append(f"Found {bidi_count} directionality / bidi override characters")
        if tag_char_count > 0:
            issues.append(f"Found {tag_char_count} tag / variation selector tracking markers")
        if em_dash_count > 0:
            issues.append(f"Found {em_dash_count} em-dash ('—') AI telltale signatures")
        if smart_quote_count > 0:
            issues.append(f"Found {smart_quote_count} smart/curved quote telltales")

        # Search for AI vocabulary telltales
        telltale_words_found = []
        for pattern in StatisticalPerturber.AI_VOCAB_SWAPS.keys():
            matches = re.findall(pattern, text, flags=re.IGNORECASE)
            if matches:
                telltale_words_found.extend(matches)

        if telltale_words_found:
            issues.append(f"Found {len(telltale_words_found)} AI vocabulary telltales: {', '.join(set(telltale_words_found[:5]))}")

        # Check AI comment signatures
        comment_matches = []
        for pattern in AICommentSanitizer.SINGLE_LINE_PATTERNS + AICommentSanitizer.MULTI_LINE_PATTERNS:
            matches = re.findall(pattern, text, flags=re.IGNORECASE)
            if matches:
                comment_matches.extend(matches)
        if comment_matches:
            issues.append(f"Found {len(comment_matches)} AI code comment signatures")

        is_clean = (len(issues) == 0)
        return {
            "status": "CLEAN" if is_clean else "WATERMARKED_OR_TELLTALES_DETECTED",
            "score": 100 if is_clean else max(0, 100 - (len(issues) * 20)),
            "issues": issues
        }


class FileMetadataSanitizer:
    """Strips EXIF, C2PA, XMP, comments, and tracking metadata from files."""

    @classmethod
    def clean_markdown_or_text(cls, content: str) -> str:
        """Removes HTML comments, AI code comments, and cleans Unicode in Markdown/Text files."""
        cleaned = re.sub(r'<!--.*?-->', '', content, flags=re.DOTALL)
        cleaned = AICommentSanitizer.clean(cleaned)
        return UnicodeSanitizer.clean(cleaned)

    @classmethod
    def clean_svg(cls, content: str) -> str:
        """Removes <metadata>, C2PA attributes, and XML comments from SVG."""
        cleaned = re.sub(r'<metadata.*?>.*?</metadata>', '', content, flags=re.DOTALL | re.IGNORECASE)
        cleaned = re.sub(r'<!--.*?-->', '', cleaned, flags=re.DOTALL)
        cleaned = re.sub(r'\s+data-(c2pa|provenance|watermark|ai|claude)="[^"]*"', '', cleaned, flags=re.IGNORECASE)
        return UnicodeSanitizer.clean(cleaned)

    @classmethod
    def clean_html(cls, content: str) -> str:
        """Removes meta tags, comments, and zero-width characters in HTML."""
        cleaned = re.sub(r'<!--.*?-->', '', content, flags=re.DOTALL)
        cleaned = re.sub(r'<meta\s+name=["\'](c2pa|provenance|generator|ai-watermark|claude)["\'].*?>', '', cleaned, flags=re.IGNORECASE)
        return UnicodeSanitizer.clean(cleaned)

    @classmethod
    def clean_file(cls, file_path: str, disrupt_image_pixels: bool = False, perturb_stats: bool = False) -> Tuple[bool, str]:
        """Detects file type and cleans watermarks, AI comments, and metadata."""
        if not os.path.exists(file_path):
            return False, f"File not found: {file_path}"

        ext = os.path.splitext(file_path)[1].lower()

        try:
            if ext in ['.md', '.txt', '.py', '.js', '.ts', '.jsx', '.tsx', '.json', '.yaml', '.yml', '.css']:
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read()
                cleaned = cls.clean_markdown_or_text(content)
                if perturb_stats:
                    cleaned = StatisticalPerturber.perturb(cleaned)
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(cleaned)
                return True, f"Sanitized code/text file: {file_path}"

            elif ext == '.svg':
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read()
                cleaned = cls.clean_svg(content)
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(cleaned)
                return True, f"Sanitized SVG file: {file_path}"

            elif ext in ['.html', '.htm']:
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read()
                cleaned = cls.clean_html(content)
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(cleaned)
                return True, f"Sanitized HTML file: {file_path}"

            elif ext in ['.png', '.jpg', '.jpeg']:
                return ImageWatermarkDisrupter.perturb_image(file_path, jitter=disrupt_image_pixels)

            elif ext == '.pdf':
                try:
                    from pypdf import PdfReader, PdfWriter
                    reader = PdfReader(file_path)
                    writer = PdfWriter()
                    for page in reader.pages:
                        writer.add_page(page)
                    with open(file_path, 'wb') as f:
                        writer.write(f)
                    return True, f"Cleared PDF metadata & annotations: {file_path}"
                except Exception as e:
                    return False, f"PDF cleaning failed: {str(e)}"

            elif ext == '.docx':
                try:
                    import docx
                    doc = docx.Document(file_path)
                    cp = doc.core_properties
                    cp.author = ""
                    cp.comments = ""
                    cp.keywords = ""
                    cp.subject = ""
                    cp.title = ""
                    for p in doc.paragraphs:
                        p.text = UnicodeSanitizer.clean(p.text)
                    doc.save(file_path)
                    return True, f"Sanitized DOCX core properties & paragraphs: {file_path}"
                except Exception as e:
                    return False, f"DOCX cleaning failed: {str(e)}"

            else:
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read()
                cleaned = UnicodeSanitizer.clean(content)
                with open(file_path, 'w', encoding='utf-8') as f:
                    f.write(cleaned)
                return True, f"Sanitized raw file: {file_path}"

        except Exception as e:
            return False, f"Error processing file {file_path}: {str(e)}"


def clean_text(text: str, perturb_stats: bool = False, clean_ai_comments: bool = True) -> str:
    """Helper function to clean raw text from zero-width watermarks, AI comments, and optional statistical markers."""
    cleaned = UnicodeSanitizer.clean(text)
    if clean_ai_comments:
        cleaned = AICommentSanitizer.clean(cleaned)
    if perturb_stats:
        cleaned = StatisticalPerturber.perturb(cleaned)
    return cleaned


def clean_file(file_path: str, disrupt_image_pixels: bool = False, perturb_stats: bool = False) -> Tuple[bool, str]:
    """Helper function to clean file metadata and watermarks."""
    return FileMetadataSanitizer.clean_file(file_path, disrupt_image_pixels=disrupt_image_pixels, perturb_stats=perturb_stats)


def audit_text(text: str) -> Dict[str, Any]:
    """Audits input text for zero-width characters, AI comments, em-dashes, and telltales."""
    return AuditTool.audit_text(text)
